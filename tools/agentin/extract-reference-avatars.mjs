function digest(path) {
  return createHash('sha256').update(readFileSync(path)).digest('hex');
}

function cropWithSips(entry, targetDirectory) {
  const source = sources[entry.source];
  const sourcePath = join(evidenceDirectory, source.file);
  const targetPath = join(targetDirectory, `${entry.id}.png`);
  if (!existsSync(sourcePath)) throw new Error(`Missing AgentIn source evidence: ${sourcePath}`);
  execFileSync('/usr/bin/sips', [
    '--cropToHeightWidth', String(entry.height), String(entry.width),
    '--cropOffset', String(entry.y), String(entry.x),
    sourcePath,
    '--out', targetPath,
  ], { stdio: 'ignore' });
  return targetPath;
}

function manifestRows(targetDirectory) {
  return crops.map((entry) => {
    const source = sources[entry.source];
    const outputPath = join(targetDirectory, `${entry.id}.png`);
    return {
      ...entry,
      sourceFile: source.file,
      outputFile: `${entry.id}.png`,
      sha256: digest(outputPath),
    };
  });
}

function renderManifest(rows) {
  const lines = [
    '# AgentIn avatar provenance manifest',
    '',
    'All avatars are deterministic crops from the user-provided Notion screenshots stored under `outputs/notion-assets/2026-09-03/agentin-current-state/`. No avatar was generated or redrawn.',
    '',
    '| Output | Source screenshot | Crop (x,y,w,h) | SHA-256 |',
    '|---|---|---:|---|',
    ...rows.map((row) => `| \`${row.outputFile}\` | \`${row.sourceFile}\` | ${row.x},${row.y},${row.width},${row.height} | \`${row.sha256}\` |`),
    '',
    `Generated by \`${relative(repositoryRoot, fileURLToPath(import.meta.url))}\`.`,
    '',
  ];
  return lines.join('\n');
}

function generate(targetDirectory) {
  mkdirSync(targetDirectory, { recursive: true });
  for (const entry of crops) cropWithSips(entry, targetDirectory);
  return manifestRows(targetDirectory);
}

if (checkMode) {
  if (!existsSync(manifestPath)) throw new Error(`Missing AgentIn avatar manifest: ${manifestPath}`);
  const temporaryDirectory = mkdtempSync(join(tmpdir(), 'agentin-avatar-check-'));
  try {
    const expectedRows = generate(temporaryDirectory);
    for (const row of expectedRows) {
      const committedPath = join(outputDirectory, row.outputFile);
      if (!existsSync(committedPath)) throw new Error(`Missing committed avatar: ${committedPath}`);
      const committedDigest = digest(committedPath);
      if (committedDigest !== row.sha256) {
        throw new Error(`Avatar is not reproducible: ${row.outputFile}`);
      }
      if (!readFileSync(manifestPath, 'utf8').includes(row.sha256)) {
        throw new Error(`Manifest does not contain digest for ${row.outputFile}`);
      }
    }
    console.log(`Verified ${expectedRows.length} AgentIn avatars.`);
  } finally {
    rmSync(temporaryDirectory, { recursive: true, force: true });
  }
} else {
  const rows = generate(outputDirectory);
  writeFileSync(manifestPath, renderManifest(rows));
  console.log(`Generated ${rows.length} AgentIn avatars and ${relative(repositoryRoot, manifestPath)}.`);
}
